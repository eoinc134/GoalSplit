"""Checks that every committed notebook is exactly what its builder produces,
and that it was executed cleanly top to bottom. Run by CI and the pre-commit
hook; run it yourself after editing a builder:

    .venv\\Scripts\\python check_notebooks.py

Notebooks are generated by notebooks/build_*.py (so their cells are reviewed
as code) and committed *with* outputs (the findings cite them). That leaves
three ways to end up with a misleading notebook, all caught here:

- a builder was edited but not re-run, or the .ipynb was edited in Jupyter
  instead of the builder → the cells differ from the builder's;
- the notebook was rebuilt but not re-executed, or executed out of order /
  partially → missing or non-sequential execution counts;
- a cell raised → an error output was committed.

It can't execute the notebooks: they need the personal dataset in
research/data/, which is never committed. Executing stays a local step
(see README.md → "Development").
"""

from __future__ import annotations

import contextlib
import io
import runpy
import sys
from dataclasses import dataclass, field
from pathlib import Path

import nbformat

# Output is plain ASCII: Windows consoles (cp1252) can't print arrows/dashes,
# and this runs in the pre-commit hook there.
NOTEBOOKS_DIR = Path(__file__).resolve().parent / "notebooks"


@dataclass
class Result:
    builder: str
    notebook: str | None = None
    problems: list[str] = field(default_factory=list)


def generate(builder: Path) -> tuple[nbformat.NotebookNode, Path]:
    """Runs a builder with nbformat.write intercepted, returning the notebook
    it would write and where — without touching the committed file."""
    captured: dict = {}
    real_write = nbformat.write

    def capture(nb, path, *args, **kwargs):
        captured["nb"], captured["path"] = nb, Path(path)

    nbformat.write = capture
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            runpy.run_path(str(builder), run_name="__main__")
    finally:
        nbformat.write = real_write
    if "nb" not in captured:
        raise RuntimeError("builder did not call nbformat.write")
    return captured["nb"], captured["path"]


def cell_signature(nb: nbformat.NotebookNode) -> list[tuple[str, str]]:
    return [(c.cell_type, c.source) for c in nb.cells]


def check_execution(nb: nbformat.NotebookNode) -> list[str]:
    problems = []
    code = [c for c in nb.cells if c.cell_type == "code"]
    counts = [c.get("execution_count") for c in code]
    if any(n is None for n in counts):
        unexecuted = sum(n is None for n in counts)
        problems.append(f"{unexecuted} of {len(code)} code cells never executed - re-run it with nbconvert --execute")
    elif counts != list(range(1, len(code) + 1)):
        problems.append(
            f"execution counts {counts} aren't 1..{len(code)} - re-run the whole notebook from a fresh kernel"
        )
    for i, c in enumerate(nb.cells):
        for out in c.get("outputs", []):
            if out.get("output_type") == "error":
                problems.append(f"cell {i} has an error output: {out.get('ename')}: {out.get('evalue', '')[:120]}")
    return problems


def check_builder(builder: Path) -> Result:
    result = Result(builder.name)
    try:
        generated, target = generate(builder)
    except Exception as err:  # a broken builder is itself the finding
        result.problems.append(f"builder failed: {type(err).__name__}: {err}")
        return result

    result.notebook = target.name
    if not target.exists():
        result.problems.append("notebook missing - run the builder, then execute it")
        return result

    committed = nbformat.read(target, as_version=4)
    try:
        nbformat.validate(committed)
    except nbformat.ValidationError as err:
        result.problems.append(f"invalid notebook: {err.message}")

    want, have = cell_signature(generated), cell_signature(committed)
    if want != have:
        differing = [i for i, (w, h) in enumerate(zip(want, have)) if w != h]
        detail = f"cells {differing[:10]} differ" if differing else ""
        if len(want) != len(have):
            detail = f"{len(have)} cells committed, builder makes {len(want)}" + (f"; {detail}" if detail else "")
        result.problems.append(
            f"out of sync with its builder ({detail}) - edit the builder, not the .ipynb; re-run it and execute"
        )
        return result  # execution state is moot until it's rebuilt

    if not committed.metadata.get("kernelspec"):
        result.problems.append("no kernelspec in metadata")
    result.problems.extend(check_execution(committed))
    return result


def main(notebooks_dir: Path = NOTEBOOKS_DIR) -> int:
    builders = sorted(notebooks_dir.glob("build_*.py"))
    results = [check_builder(b) for b in builders]

    built = {r.notebook for r in results if r.notebook}
    orphans = sorted(p.name for p in notebooks_dir.glob("*.ipynb") if p.name not in built)

    failed = False
    for r in results:
        label = f"{r.builder} -> {r.notebook or '?'}"
        if r.problems:
            failed = True
            print(f"FAIL {label}")
            for p in r.problems:
                print(f"     - {p}")
        else:
            print(f"ok   {label}")
    for name in orphans:
        failed = True
        print(f"FAIL {name}\n     - no build_*.py writes this notebook")

    print(f"\n{len(results)} notebooks checked, {'problems found' if failed else 'all in sync and cleanly executed'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]) if len(sys.argv) > 1 else NOTEBOOKS_DIR))
